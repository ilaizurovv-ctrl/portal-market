class CompatRow(dict):
 def __getitem__(self,key):
  if isinstance(key,int): return list(self.values())[key]
  return super().__getitem__(key)

class PgCursor:
 def __init__(self,cur): self.cur=cur; self.lastrowid=None
 def execute(self,sql,params=()):
  import re
  q=sql.strip()
  if q.upper().startswith("PRAGMA TABLE_INFO"):
   table=re.search(r"\\(([^)]+)\\)",q).group(1).strip()
   self.cur.execute("SELECT column_name AS name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position",(table,))
   return self
  ignore=q.upper().startswith("INSERT OR IGNORE")
  if ignore: q=re.sub(r"^INSERT OR IGNORE", "INSERT", q, flags=re.I)
  q=q.replace("?","%s")
  if ignore: q += " ON CONFLICT DO NOTHING"
  else:
   m=re.match(r"INSERT INTO (users|messages|chats|chat_messages|star_transactions)\\b",q,re.I)
   if m and " RETURNING " not in q.upper(): q += " RETURNING id"
  self.cur.execute(q,params)
  if q.upper().startswith("INSERT INTO") and " RETURNING ID" in q.upper():
   row=self.cur.fetchone()
   if row:self.lastrowid=row["id"]
  return self
 def fetchone(self):
  r=self.cur.fetchone()
  return CompatRow(r) if r is not None and not isinstance(r,dict) else r
 def fetchall(self):
  return [CompatRow(r) if not isinstance(r,dict) else r for r in self.cur.fetchall()]
 def executescript(self,script):
  for statement in script.split(";"):
   statement=statement.strip()
   if statement:self.execute(statement)
  return self

class PgConnection:
 def __init__(self):
  import psycopg
  from psycopg.rows import dict_row
  self.conn=psycopg.connect(DATABASE_URL,row_factory=dict_row)
 def __enter__(self): return self
 def __exit__(self,typ,val,tb):
  if typ:self.conn.rollback()
  else:self.conn.commit()
  self.conn.close()
 def execute(self,sql,params=()):
  if sql.strip().upper().startswith("PRAGMA"):
   return PgCursor(self.conn.cursor()).execute(sql,params)
  return PgCursor(self.conn.cursor()).execute(sql,params)
 def executescript(self,script):
  cur=PgCursor(self.conn.cursor())
  for statement in script.split(";"):
   statement=statement.strip()
   if not statement:continue
   statement=statement.replace("INTEGER PRIMARY KEY AUTOINCREMENT","BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
   statement=statement.replace("INTEGER PRIMARY KEY","BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
   statement=statement.replace(" INTEGER NOT NULL"," BIGINT NOT NULL")
   statement=statement.replace(" INTEGER,"," BIGINT,")
   cur.execute(statement)
  return cur
 def commit(self): self.conn.commit()

