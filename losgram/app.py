def hp(p,s=None):
 s=s or secrets.token_bytes(16); return s.hex()+"$"+hashlib.pbkdf2_hmac("sha256",p.encode(),s,210000).hex()
def check(p,v):
 try:
  s,d=v.split("$",1); return hmac.compare_digest(hp(p,bytes.fromhex(s)).split("$",1)[1],d)
 except: return False
def token(uid):
 p=f"{uid}:{int(time.time())}"; return p+":"+hmac.new(SECRET.encode(),p.encode(),hashlib.sha256).hexdigest()
def uid(t):
 try:
  a,b,s=t.split(":"); p=a+":"+b
  if not SECRET or not hmac.compare_digest(s,hmac.new(SECRET.encode(),p.encode(),hashlib.sha256).hexdigest()) or int(b)<time.time()-31536000:return None
  return int(a)
 except:return None
